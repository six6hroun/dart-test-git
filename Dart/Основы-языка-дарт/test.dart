import 'dart:io';

//Примитивы и строки
/*Пользователь вводит свое полное имя (например, Иван Иванов). 
Программа должна вывести приветствие, количество символов в имени и имя, написанное капсом (заглавными буквами).*/
void test1(){
  stdout.write("Введите свое имя: ");
  String? name = stdin.readLineSync();
  if (name == null){
    print("Вы ввели пустую строку или вышли из строки ввода");
    return;
  }
  var count = name.length;
  var capsname = name.toUpperCase();
  print("Привет ${name}! Количество символов в твоем имени: ${count}. Твое имя заглавными буквами: ${capsname}");
}

/*Задача 2. Null Safety и парсинг
Задача: Программа просит ввести возраст. Если пользователь ввел число (например, 18), 
программа выводит: "Через 5 лет тебе будет 23". Если пользователь ввел текст или ничего не ввел (null),
программа должна вывести: "Ошибка: нужно ввести число". */
void test2(){
  stdout.write("Введите свой возраст: "); 
  String? age = stdin.readLineSync();
  int? numage = int.tryParse(age ?? "");
  if (numage == null){
    print("Ошибка! вы не ввели число");
    return;
  }
  int addage = numage + 5;
  print("Через 5 лет вам будет ${addage}");
}

/*Задача 3. Условия (If/Else)
Задача: Программа просит ввести температуру на улице (целое число).
Если больше 25 — вывести "Жарко, можно в шортах".
Если от 10 до 25 включительно — вывести "Нормально, надевай куртку".
Если меньше 10 — вывести "Холодно, сиди дома". */
void test3(){
  stdout.write("Введите температуру воздуха: "); String? temp = stdin.readLineSync();
  int? numTemp = int.tryParse(temp ?? "");
  if (numTemp == null){
    print("Вы некорректно ввели температуру!");
    return;
  } else if (numTemp > 25){
    print("Жарко, можно в шортах");
  } else if (numTemp >= 10 && numTemp <= 25){
    print("Нормально, надевай куртку");
  } else{
    print("Холодно, сиди дома");
  }
}

/*Задача 4. Циклы и математика
Задача: Программа просит ввести число N (например, 5). С помощью цикла for выведи таблицу умножения для этого числа от 1 до 5.
(Пример вывода для 5: 5 * 1 = 5, 5 * 2 = 10 и т.д.) */
void test4(){
  stdout.write("Введите число: "); String? n = stdin.readLineSync();
  int? number = int.tryParse(n ?? "");
  if (number == null){
    print("Введите корректное число");
    return;
  } else {
    for (int i = 1; i <= number; i++){
      print("$number * $i = ${number*i}");
    }
  }
}

/*Задача 5. Циклы и поиск (Хардкорчик)
Задача: Загадай в коде любое число (например, 7). 
Программа в цикле просит пользователя угадать это число. 
Если ввел меньше — пишет "Загаданное число больше". 
Если больше — "Загаданное число меньше". 
Пока не угадает, цикл не завершается. Когда угадает — пишет "Победа!" и выходит из цикла.*/
void test5(){
  int value = 7;
  while (true){
    stdout.write("Введите число которое хотите угадать: "); String? n = stdin.readLineSync();
    int? newn = int.tryParse(n ?? "");
    if (newn == null){
      print("Вы не ввели цифру");
      continue;
    } else if (newn < value){
      print("Введеное вами число меньше загаданого");
    } else if (newn > value){
      print("Введеное вами число больше загаданого");
    } else {
      print("Вы угадали число! Поздравляем!");
      break;
    }
  }
}

void main()
{
  test5();
}