//Условные операторы в дарт
void main(){
  c=a|b; //(c равно true, если либо a, либо b (либо и a, и b) равны true, иначе c будет равно false)
  c=a&b; //(c равно true, если и a, и b равны true, иначе c будет равно false)
  c=!b; //(c равно true, если b равно false, иначе c будет равно false)
  c=a^b; //(c равно true, если либо a, либо b (но не одновременно) равны true, иначе c будет равно false)
  c=a||b; //(c равно true, если либо a, либо b (либо и a, и b) равны true, иначе c будет равно false) вначале будет вычисляться значение a, и если оно равно true, то вычисление значения b уже смысла не имеет
  c=a&&b; //(c равно true, если и a, и b равны true, иначе c будет равно false) вначале будет вычисляться значение a, и если оно равно true, то вычисление значения b уже смысла не имеет


  const int num1 = 8;
