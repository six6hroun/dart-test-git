//Перемнные и константы в языке Dart
void main() {
  String name = "Гурыч";
  int age = 21;
  double height = 1.72;
  print("Меня зовут $name, мне $age год, мой рост $height метра");

  //var сам определяет тип присваемой перемнной, но переопределять нельзя (только на значение того же типа)
  var name2 = "Гурыч";
  name2 = "21"; // Ошибка, так как переменная name2 уже определена как String

  //dynamic сам определяет тип присваемой перемнной, но позволяет переопределить переменную
  dynamic name3 = "Гурыч";
  name3 = 21; //Нормально, так как переменная name3 определена как dynamic

  const pi = 3.14; //Константа, которая не может быть переопределена и должна быть инициализирована при объявлении
  final pi2 = 3.14; //Константа, которая не может быть переопределена, но может быть инициализирована позже
}